import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const base=path.dirname(fileURLToPath(import.meta.url));
const data=JSON.parse(await fs.readFile(path.join(base,'first_shift_analysis.json'),'utf8'));
const wb=Workbook.create();
const serial=iso=>iso ? (Date.parse(iso.slice(0,19)+'Z')-Date.UTC(1899,11,30))/86400000 : null;
const safe=value=>typeof value==='string' && /^[=+@-]/.test(value) ? "'"+value:value;
const headers=['Dátum','Futár neve','Futár ID','Első Route ID','Raktár','Első műszak\ntervezett kezdete','Hub tényleges\nkezdés','Giriton-belépés\n(napi első)','Sorbaállási\nesemény ideje','Hub\nbesorolás','Kezdési eltérés\n(perc)','Megjegyzés'];
for (const [name,rows,all] of [['Első műszak késések',data.late,false],['Napi első műszakok',data.first,true]]) {
 const sh=wb.worksheets.add(name);sh.showGridLines=false;
 const end=10+rows.length;
 sh.getRange(`A1:L${end}`).format.font={name:'Arial',size:10,color:'#202B38'};
 sh.getRange(`A1:L${end}`).format.verticalAlignment='center';
 sh.getRange('A2').values=[[all?'Napi első műszakok és Giriton-belépés':'Első műszak késése a Hub értékelése szerint']];
 sh.getRange('A2').format.font={name:'Arial',size:14,bold:true,color:'#1F3655'};
 sh.getRange('A2:L2').format.rowHeight=29;
 sh.getRange('A2:L2').format.borders={bottom:{style:'thin',color:'#9BACBE'}};
 sh.getRange('A3').values=[['2026. október 1–31. · JITT · BUD1 és BUD2 · Idők: Europe/Budapest']];
 sh.getRange('A4').values=[[all?'Naponta és futáronként a legkorábbi tervezett műszak szerepel, a Hub eredeti értékelésével.':'Kiválasztás: naponta és futáronként a legkorábbi tervezett műszak, amelynek eredeti Hub-besorolása LATE.']];
 sh.getRange('A5').values=[['Műszakok:']];
 sh.getRange('C5').formulas=[[`=COUNTA(C11:C${end})`]];
 sh.getRange('D5').values=[[all?'LATE tételek:':'Érintett futárok:']];
 if(all)sh.getRange('F5').formulas=[[`=COUNTIFS(J11:J${end},"LATE")`]];
 else sh.getRange('F5').values=[[data.summary.late_couriers]];
 sh.getRange('G5').values=[['Giriton-idő nélkül:']];
 sh.getRange('I5').formulas=[[`=COUNTBLANK(H11:H${end})`]];
 sh.getRange('A6').values=[['A Giriton-idő a napi első belépés. A sorbaállás az első kapcsolódó túra kiosztását megelőző utolsó SHIFT_AVAILABLE esemény.']];
 sh.getRange('A7').values=[['Forrás: Hub havi shifts válasz (2026-10-31 23:32–23:33), route-detail eseménynapló, Giriton attendance. Lekérés: 2026-11-12.']];
 sh.getRange('A8').values=[['Hub-eltérés: a havi összesítő 121, a napi LATE sorok száma 120. Komjáti Ákos (8185), BUD2: havi 1, napi 0; dátum és Route ID nem azonosítható.']];
 sh.getRange('A9').values=[['A LATE-listán 5 esetben nincs egyező Route ID, 4 esetben nincs Giriton-idő, 12 esetben nincs sorbaállási esemény. A hiányzó mezők üresek.']];
 sh.getRange('A3:L9').format.rowHeight=21;
 sh.getRange('A3').format.font={italic:true,color:'#57677B'};
 sh.getRange('A7:L7').format.font={size:9,color:'#57677B'};
 sh.getRange('A8').format.font={color:'#8A4B12',size:10};
 sh.getRange('A10:L10').values=[headers];
 const values=rows.map(r=>{
  const notes=[r.notes,r.login_note,r.route_match==='Tényleges műszakkezdés egyezik; eltérő route-terv'?r.route_match:'',r.other_routes?'További túra ugyanebben a műszakban: '+r.other_routes:''].filter(Boolean).join('; ');
  return [serial(r.date+'T00:00:00'),safe(r.name),r.courier_id,r.route_id,r.warehouse,serial(r.planned),serial(r.actual),serial(r.login),serial(r.queue),r.evaluation,null,safe(notes)];
 });
 sh.getRange(`A11:L${end}`).values=values;
 sh.tables.add(`A10:L${end}`,true,all?'FirstShifts':'LateFirstShifts');
 sh.getRange('A10:L10').format={fill:'#263E5B',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},wrapText:true,horizontalAlignment:'center',verticalAlignment:'center',rowHeight:40};
 sh.getRange(`A11:A${end}`).setNumberFormat('yyyy-mm-dd');
 sh.getRange(`F11:I${end}`).setNumberFormat('hh:mm:ss');
 sh.getRange(`C11:E${end}`).setNumberFormat('@');
 sh.getRange(`K11:K${end}`).formulas=rows.map((_,i)=>[`=IF(OR(F${11+i}="",G${11+i}=""),"",(G${11+i}-F${11+i})*1440)`]);
 sh.getRange(`K11:K${end}`).setNumberFormat('0.00');
 sh.getRange(`F11:K${end}`).format.horizontalAlignment='right';
 sh.getRange(`A11:L${end}`).format.rowHeight=23;
 const widths={A:12,B:28,C:10,D:13,E:9,F:21,G:20,H:21,I:21,J:17,K:18,L:135};
 for(const [col,width] of Object.entries(widths))sh.getRange(`${col}1:${col}${end}`).format.columnWidth=width;
 sh.freezePanes.freezeRows(10);sh.freezePanes.freezeColumns(4);
 sh.tabColor=all?'#70859D':'#263E5B';
 sh.getRange(`H11:H${end}`).conditionalFormats.add('containsBlanks',{format:{fill:'#FFF0CC'}});
 sh.getRange(`D11:D${end}`).conditionalFormats.add('containsBlanks',{format:{fill:'#FFF0CC'}});
 sh.getRange(`J11:J${end}`).conditionalFormats.add('containsText',{text:'LATE',format:{fill:'#FCE5DE',font:{color:'#A53924',bold:true}}});
}
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:"'Első műszak késések'!A10:K13",include:'values,formulas',tableMaxRows:4,tableMaxCols:11,maxChars:2600})).ndjson);
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!',options:{useRegex:true,maxResults:20},summary:'Formula scan',maxChars:1000})).ndjson);
const xlsx=await SpreadsheetFile.exportXlsx(wb);
await xlsx.save(path.join(base,'oktober_elso_muszak_hub_giriton_2026.xlsx'));
for(const [sheetName,file] of [['Első műszak késések','first_late_preview.png'],['Napi első műszakok','first_all_preview.png']]) {
 const img=await wb.render({sheetName,range:'A1:K15',scale:1.4,format:'png'});
 await fs.writeFile(path.join(base,file),new Uint8Array(await img.arrayBuffer()));
}
console.log('Saved corrected first-shift workbook.');
