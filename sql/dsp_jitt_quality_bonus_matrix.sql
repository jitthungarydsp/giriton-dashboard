insert into public.dsp_jitt_quality_bonus_matrix (
    metric_type,
    level_code,
    level_label,
    courier_level_label,
    day_type,
    route_type,
    route_type_label,
    threshold_min,
    threshold_max,
    threshold_min_inclusive,
    threshold_max_inclusive,
    duration_min_hours,
    duration_max_hours,
    duration_label,
    company_amount_huf,
    courier_amount_huf,
    calculation_unit,
    source,
    note,
    valid_from,
    priority,
    is_active
)
select
    metric_bands.metric_type,
    metric_bands.level_code,
    metric_bands.level_label,
    metric_bands.courier_level_label,
    'any',
    duration_bands.route_type,
    duration_bands.route_type_label,
    metric_bands.threshold_min,
    metric_bands.threshold_max,
    metric_bands.threshold_min_inclusive,
    metric_bands.threshold_max_inclusive,
    duration_bands.duration_min_hours,
    duration_bands.duration_max_hours,
    duration_bands.duration_label,
    case metric_bands.level_code
        when 1 then duration_bands.company_l1
        when 2 then duration_bands.company_l2
        when 3 then duration_bands.company_l3
        else duration_bands.company_l4
    end,
    case metric_bands.level_code
        when 1 then duration_bands.courier_l1
        when 2 then duration_bands.courier_l2
        when 3 then duration_bands.courier_l3
        else duration_bands.courier_l4
    end,
    'per_route',
    'jitt_contract_2026_matrix',
    'DSP/JITT quality matrix from the latest spreadsheet screenshot. Express and city are active; regional is stored but inactive.',
    date '2026-01-01',
    case when metric_bands.metric_type = 'delay' then 0 else 1000 end
        + metric_bands.level_code * 100
        + duration_bands.duration_order,
    duration_bands.is_active
from metric_bands
cross join duration_bands;

