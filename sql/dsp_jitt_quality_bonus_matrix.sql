create table if not exists public.dsp_jitt_quality_bonus_matrix (
    id bigint generated by default as identity primary key,
    metric_type text not null check (metric_type in ('delay', 'compliance')),
    level_code integer not null check (level_code between 1 and 4),
    level_label text not null,
    courier_level_label text not null,
    day_type text not null default 'any',
    route_type text not null default 'any' check (route_type in ('express', 'normal', 'regional', 'any')),
    route_type_label text not null,
    warehouse_code text,
    threshold_min numeric(8, 4),
    threshold_max numeric(8, 4),
    threshold_min_inclusive boolean not null default true,
    threshold_max_inclusive boolean not null default true,
    duration_min_hours numeric(5, 4),
    duration_max_hours numeric(5, 4),
    duration_label text not null,
    company_amount_huf integer not null default 0 check (company_amount_huf >= 0),
    courier_amount_huf integer not null default 0 check (courier_amount_huf >= 0),
    calculation_unit text not null default 'per_route' check (calculation_unit in ('fixed', 'per_route', 'per_order', 'per_hour')),
    source text not null default 'manual',
    note text,
    valid_from date not null default date '2026-01-01',
    valid_to date,
    priority integer not null default 100,
    is_active boolean not null default true,
    updated_at timestamptz not null default now(),
    created_at timestamptz not null default now()
);

alter table public.dsp_jitt_quality_bonus_matrix
    add column if not exists courier_level_label text not null default '',
    drop constraint if exists dsp_jitt_quality_bonus_matrix_level_code_check,
    add constraint dsp_jitt_quality_bonus_matrix_level_code_check check (level_code between 1 and 4);

create index if not exists dsp_jitt_quality_bonus_matrix_lookup_idx
    on public.dsp_jitt_quality_bonus_matrix (
        metric_type,
        route_type,
        is_active,
        priority,
        threshold_min,
        threshold_max,
        duration_min_hours,
        duration_max_hours
    );

