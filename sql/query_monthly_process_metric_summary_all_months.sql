-- Havi elszámolási folyamat- és reklamációs mutatók minden mentett hónapra.
-- Futás helye: Supabase SQL Editor

select
    period_start as honap,
    calculated_at as utolso_mentes,
    calculated_by as mentette,
    completed_flow_count as teljesen_lezart_folyamat,
    complaint_flow_count as reklamacioval_erintett_folyamat,
    complaint_total as reklamaciok_szama,
    source_counts ->> 'courier_month_count' as futar_honap_db,
    source_counts ->> 'finance_covered_couriers' as penzugyi_forrassal_futar_db,
    source_counts ->> 'response_timed_count' as merheto_valaszido_db,
    definition_version as szamitas_verzio,
    complaints_average as reklamacio_atlag_futar_honaponkent,
    response_count as megvalaszolt_reklamacio,
    response_average_hours as reklamacio_valaszido_atlag_ora,
    response_median_hours as reklamacio_valaszido_median_ora,
    malus_total_huf as malusz_osszesen_ft,
    other_deductions_total_huf as egyeb_levonas_osszesen_ft,
    deductions_total_huf as levonasok_osszesen_ft,
    deductions_average_huf as levonas_atlag_folyamatonkent_ft,
    opening_to_settlement ->> 'count' as megnyitas_elfogadas_db,
    opening_to_settlement ->> 'average_hours' as megnyitas_elfogadas_atlag_ora,
    opening_to_settlement ->> 'median_hours' as megnyitas_elfogadas_median_ora,
    settlement_to_tig ->> 'count' as elfogadas_tig_db,
    settlement_to_tig ->> 'average_hours' as elfogadas_tig_atlag_ora,
    settlement_to_tig ->> 'median_hours' as elfogadas_tig_median_ora,
    tig_to_invoice ->> 'count' as tig_szamla_db,
    tig_to_invoice ->> 'average_hours' as tig_szamla_atlag_ora,
    tig_to_invoice ->> 'median_hours' as tig_szamla_median_ora,
    invoice_to_paid ->> 'count' as szamla_kifizetes_db,
    invoice_to_paid ->> 'average_hours' as szamla_kifizetes_atlag_ora,
    invoice_to_paid ->> 'median_hours' as szamla_kifizetes_median_ora,
    opening_to_paid ->> 'count' as teljes_atfutas_db,
    opening_to_paid ->> 'average_hours' as teljes_atfutas_atlag_ora,
    opening_to_paid ->> 'median_hours' as teljes_atfutas_median_ora,
    with_complaint_flow_count as reklamacioval_folyamat_db,
    with_complaint_deductions_huf as reklamacioval_levonas_osszesen_ft,
    with_complaint_deductions_average_huf as reklamacioval_levonas_atlag_ft,
    without_complaint_flow_count as reklamacio_nelkul_folyamat_db,
    without_complaint_deductions_huf as reklamacio_nelkul_levonas_osszesen_ft,
    without_complaint_deductions_average_huf as reklamacio_nelkul_levonas_atlag_ft
from settlement.monthly_process_metric_summary
order by period_start desc;
